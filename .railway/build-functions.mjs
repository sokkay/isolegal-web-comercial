import { build } from "esbuild";
import { readFile, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

export async function buildRiskCron({
  versionedImports = true,
  outfile = ".railway/functions/risk-calculator-cron.mjs",
} = {}) {
  const templateDirectory = new URL("../lib/email/templates/", import.meta.url);
  const templates = Object.fromEntries(
    await Promise.all(
      (await readdir(templateDirectory)).map(async (name) => [
        name,
        await readFile(new URL(name, templateDirectory), "utf8"),
      ])
    )
  );
  return build({
    entryPoints: [
      fileURLToPath(new URL("src/risk-calculator-cron.ts", import.meta.url)),
    ],
    bundle: true,
    packages: "external",
    format: "esm",
    platform: "node",
    target: "es2022",
    outfile,
    banner: {
      js: "// Generated by pnpm railway:build. Edit .railway/src/ and lib/email/ instead.",
    },
    plugins: [
      {
        name: "embedded-email-templates",
        setup(builder) {
          builder.onResolve({ filter: /^node:fs$/ }, () => ({
            path: "templates",
            namespace: "embedded",
          }));
          builder.onLoad({ filter: /.*/, namespace: "embedded" }, () => ({
            contents: `import path from "node:path";
const templates = ${JSON.stringify(templates)};
export function readFileSync(file) {
  const template = templates[path.basename(file)];
  if (template === undefined) throw new Error("Unknown email template");
  return template;
}`,
          }));
          if (versionedImports) {
            for (const name of [
              "pocketbase",
              "handlebars",
              "zod",
              "posthog-node",
            ]) {
              builder.onResolve(
                { filter: new RegExp(`^${name}$`) },
                async () => {
                  const { version } = JSON.parse(
                    await readFile(`node_modules/${name}/package.json`, "utf8")
                  );
                  return { path: `${name}@${version}`, external: true };
                }
              );
            }
          }
        },
      },
    ],
  });
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await buildRiskCron();
}
